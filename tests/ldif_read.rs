#[test]
fn an_empty_file_is_no_records_and_not_an_error() {
    // `ldapadd` on an empty file is a legitimate no-op, and a script that generated nothing
    // should not fail.
    assert!(parse("").is_empty());
    assert!(parse("\n\n\n").is_empty());
    assert!(parse("# only a comment\n").is_empty());
}

#[test]
fn a_document_that_opens_with_version_1_parses() {
    // Every `slapcat` dump opens with it (RFC 2849 §3.1), so a reader that refused it would
    // refuse the output of the tool it exists to accept.
    let records = parse(
        "version: 1

dn: cn=a,dc=example,dc=com
cn: a

",
    );

    assert_eq!(records.len(), 1, "the version line is not a record");
    let Record::Entry(entry) = &records[0] else {
        panic!("expected an entry");
    };
    assert_eq!(entry.entry.dn(), "cn=a,dc=example,dc=com");
}

#[test]
fn a_version_this_reader_does_not_know_is_refused() {
    // Silently ignoring it would import a file written for a format this reader does not
    // implement, and the first symptom would be a value that changed.
    let err = refuse(
        "version: 2

dn: cn=a,dc=example,dc=com
cn: a

",
    );
    assert!(err.to_string().contains("version: 2"), "{err}");
}

#[test]
fn a_bare_line_continuation_at_the_start_is_refused() {
    // A file whose first character is a space is truncated at the top, not folded.
    let err = refuse(" cn=a,dc=example,dc=com\n");
    assert!(err.to_string().contains('1'), "{err}");
}

#[test]
fn crlf_line_endings_are_accepted() {
    // Files written on Windows and files passed through a mail system arrive with CRLF; a
    // reader that kept the CR would put it in every value.
    let records = parse("dn: cn=a,dc=example,dc=com\r\ncn: a\r\n\r\n");
    let Record::Entry(entry) = &records[0] else {
        panic!("expected an entry");
    };
    assert_eq!(
        entry
            .entry
            .attributes()
            .get("cn")
            .and_then(|attribute| attribute.values.first())
            .map(String::as_str),
        Some("a")
    );
}

#[test]
fn a_200_character_value_survives_a_round_trip_through_the_exporter() {
    // The exporter folds at 76 octets; the reader has to join it back exactly, or a long
    // description changes every time a directory is exported and imported.
    let long = "ж".repeat(200);
    let entry = rust_rest_ldap::model::Entry::new(
        "cn=a,dc=example,dc=com",
        rust_rest_ldap::model::Attributes::new()
            .push(rust_rest_ldap::model::Attribute::single("cn", "a"))
            .push(rust_rest_ldap::model::Attribute::single(
                "description",
                &long,
            )),
    );

    let text = rust_rest_ldap::ldif::export(&[entry], rust_rest_ldap::ldif::Options::default());
    let records = parse(&text);

    let Record::Entry(parsed) = &records[0] else {
        panic!("expected an entry");
    };
    assert_eq!(
        parsed
            .entry
            .attributes()
            .get("description")
            .and_then(|attribute| attribute.values.first())
            .map(String::as_str),
        Some(long.as_str()),
        "the value must come back byte for byte, folding included"
    );
}

#[test]
fn a_whole_exported_directory_reads_back_as_itself() {
    // The property F5 depends on: export, import, export again, and the two documents are
    // the same. Anything the reader loses shows up here rather than in a migration.
    let entries: Vec<_> = (0..5)
        .map(|index| {
            rust_rest_ldap::model::Entry::new(
                format!("cn=user{index},dc=example,dc=com"),
                rust_rest_ldap::model::Attributes::new()
                    .push(rust_rest_ldap::model::Attribute::single(
                        "cn",
                        &format!("user{index}"),
                    ))
                    .push(rust_rest_ldap::model::Attribute::single("sn", "Иванов"))
                    .push(rust_rest_ldap::model::Attribute::new(
                        "mail",
                        vec![
                            format!("user{index}@example.com"),
                            format!("u{index}@example.com"),
                        ],
                    )),
            )
        })
        .collect();

    let text = rust_rest_ldap::ldif::export(&entries, rust_rest_ldap::ldif::Options::default());
    let records = parse(&text);
    assert_eq!(records.len(), entries.len());

    let parsed: Vec<_> = records
        .into_iter()
        .map(|record| match record {
            Record::Entry(entry) => entry.entry,
            other => panic!("expected entries, got {other:?}"),
        })
        .collect();

    assert_eq!(
        rust_rest_ldap::ldif::export(&parsed, rust_rest_ldap::ldif::Options::default()),
        text
    );
}
