#[test]
fn a_modify_record_carries_its_modifications_in_order() {
    let records = parse(
        "dn: cn=alice,dc=example,dc=com
changetype: modify
add: mail
mail: alice@example.com
-
delete: description
-
replace: sn
sn: Brown

",
    );

    assert_eq!(records.len(), 1);
    let Record::Change(change) = &records[0] else {
        panic!("expected a change, got {:?}", records[0]);
    };

    assert_eq!(change.dn, "cn=alice,dc=example,dc=com");
    assert_eq!(change.change, Change::Modify);

    assert_eq!(change.modifications.len(), 3, "three specifications");
    assert_eq!(change.modifications[0].op, ModOp::Add);
    assert_eq!(change.modifications[0].attribute, "mail");
    assert_eq!(change.modifications[0].values, vec!["alice@example.com"]);

    assert_eq!(change.modifications[1].op, ModOp::Delete);
    assert!(
        change.modifications[1].values.is_empty(),
        "a delete with no values removes the whole attribute"
    );

    assert_eq!(change.modifications[2].op, ModOp::Replace);
    assert_eq!(change.modifications[2].values, vec!["Brown"]);
}

#[test]
fn one_specification_may_carry_several_values() {
    let records = parse(
        "dn: cn=a,dc=example,dc=com
changetype: modify
add: mail
mail: a@example.com
mail: b@example.com

",
    );

    let Record::Change(change) = &records[0] else {
        panic!("expected a change");
    };
    assert_eq!(change.modifications.len(), 1);
    assert_eq!(
        change.modifications[0].values,
        vec!["a@example.com", "b@example.com"]
    );
}

#[test]
fn a_delete_record_names_the_entry_and_nothing_else() {
    let records = parse("dn: cn=a,dc=example,dc=com\nchangetype: delete\n\n");

    let Record::Change(change) = &records[0] else {
        panic!("expected a change");
    };
    assert_eq!(change.change, Change::Delete);
    assert!(change.modifications.is_empty());
}

#[test]
fn a_moddn_record_carries_the_new_name() {
    let records = parse(
        "dn: cn=a,dc=example,dc=com
changetype: modrdn
newrdn: cn=b
deleteoldrdn: 1

",
    );

    let Record::Change(change) = &records[0] else {
        panic!("expected a change");
    };
    assert_eq!(change.change, Change::ModDn);
    assert_eq!(change.new_rdn.as_deref(), Some("cn=b"));
    assert_eq!(change.delete_old_rdn, Some(true));
    assert!(change.new_superior.is_none());
}

#[test]
fn a_moddn_record_may_name_a_new_parent() {
    let records = parse(
        "dn: cn=a,ou=users,dc=example,dc=com
changetype: modrdn
newrdn: cn=b
deleteoldrdn: 0
newsuperior: ou=staff,dc=example,dc=com

",
    );

    let Record::Change(change) = &records[0] else {
        panic!("expected a change");
    };
    assert_eq!(change.delete_old_rdn, Some(false));
    assert_eq!(
        change.new_superior.as_deref(),
        Some("ou=staff,dc=example,dc=com")
    );
}

#[test]
fn a_moddn_record_without_a_new_rdn_is_refused() {
    let err = refuse("dn: cn=a,dc=example,dc=com\nchangetype: modrdn\ndeleteoldrdn: 1\n\n");
    assert!(err.to_string().contains("newrdn"), "{err}");
}

#[test]
fn a_modify_record_with_no_modifications_is_refused() {
    // An empty modify would be accepted by the server and change nothing; the file is wrong
    // and saying so is the point of reading it.
    let err = refuse("dn: cn=a,dc=example,dc=com\nchangetype: modify\n\n");
    assert!(err.to_string().contains("modif"), "{err}");
}

#[test]
fn a_change_type_that_does_not_exist_is_refused_by_name() {
    let err = refuse("dn: cn=a,dc=example,dc=com\nchangetype: rename\n\n");
    let text = err.to_string();
    assert!(
        text.contains("rename"),
        "the refusal must quote what was written: {text}"
    );
}

#[test]
fn a_modification_operator_that_does_not_exist_is_refused_by_name() {
    let err = refuse(
        "dn: cn=a,dc=example,dc=com
changetype: modify
increment: mail
mail: a@example.com

",
    );
    assert!(err.to_string().contains("increment"), "{err}");
}

#[test]
fn a_value_before_any_operator_is_refused() {
    // `mail: x` with no `add:` before it would otherwise attach to nothing and be dropped.
    let err = refuse(
        "dn: cn=a,dc=example,dc=com
changetype: modify
mail: a@example.com

",
    );
    let text = err.to_string();
    assert!(
        text.contains("mail") && text.contains("add"),
        "the refusal must say what to write instead: {text}"
    );
}

#[test]
fn a_dash_inside_an_entry_record_is_refused_rather_than_taken_as_a_value() {
    // `-` is only meaningful in a modify record. In an entry it is a line that is not an
    // attribute, and accepting it would hide a file that mixes the two.
    let err = refuse("dn: cn=a,dc=example,dc=com\ncn: a\n-\n\n");
    assert!(err.to_string().contains("line 3"), "{err}");
}

