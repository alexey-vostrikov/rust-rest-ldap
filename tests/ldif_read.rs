//! The LDIF reader: RFC 2849, the format every directory tool speaks.
//!
//! The rules that make this file worth its length are the ones that fail quietly:
//!
//! - a folded line whose continuation is missing loses half a value and the entry still
//!   parses;
//! - `::` means base64 and `:<` means "read the value from a URL": treating either as plain
//!   text produces a valid-looking entry with the wrong contents;
//! - `-` separates the specifications of one `changetype: modify`, and reading it as part of
//!   a value merges two changes into one;
//! - a file with no trailing blank line ends its last record implicitly, not not-at-all.

use rust_rest_ldap::ldif_read::{self, Change, Error, ModOp, Record};

/// Parses, expecting success.
fn parse(text: &str) -> Vec<Record> {
    ldif_read::parse(text).expect("the file must parse")
}

/// Parses, expecting a refusal, and returns the message.
fn refuse(text: &str) -> Error {
    ldif_read::parse(text).expect_err("the file must be refused")
}

